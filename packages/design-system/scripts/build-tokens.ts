/**
 * Compiles tokens/tokens.json (W3C DTCG format) into one output per platform:
 *
 *   src/styles/theme.css           Web. Tailwind v4 theme + light/dark CSS variable scopes.
 *   src/tokens/tokens.generated.ts Native (and docs). Typed values; dimensions as px numbers.
 *
 *   node scripts/build-tokens.ts          write both files
 *   node scripts/build-tokens.ts --check  exit 1 if a committed output is stale (CI)
 *
 * The web theme *replaces* Tailwind's default palette and scales, so only Mal tokens
 * exist as utilities: `bg-emerald-600` or `p-7` don't compile. That's the cheapest
 * governance there is.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const path = (rel: string) => fileURLToPath(new URL(`../${rel}`, import.meta.url));
const HEADER = 'AUTO-GENERATED by scripts/build-tokens.ts from tokens/tokens.json. Do not edit by hand.';

/* ------------------------------- read + resolve ------------------------------- */

type Token = { $value: unknown };
type Group = { [key: string]: Group | Token | string };
interface ShadowLayer { color: string; offsetX: string; offsetY: string; blur: string; spread: string }

const json = JSON.parse(readFileSync(path('tokens/tokens.json'), 'utf8')) as Group;

/** Leaf tokens of a group, skipping $type/$description metadata. */
function leaves<T>(group: Group): Array<[string, T]> {
  return Object.entries(group)
    .filter(([k]) => !k.startsWith('$'))
    .map(([k, v]) => [k, (v as Token).$value as T]);
}

/** Resolves a DTCG alias like "{palette.sand.50}" to its value. */
function resolve(value: string): string {
  const ref = /^\{(.+)\}$/.exec(value)?.[1];
  if (!ref) return value;
  const target = ref.split('.').reduce<unknown>((node, key) => (node as Group)?.[key], json) as Token | undefined;
  if (!target || !('$value' in target)) throw new Error(`Unresolved token reference ${value}`);
  return resolve(target.$value as string);
}

const px = (dim: string) => Number(dim.replace('px', ''));
const rem = (dim: string) => (px(dim) === 0 ? '0' : `${px(dim) / 16}rem`);
const ms = (d: string) => Number(d.replace('ms', ''));

const group = (name: string) => json[name] as Group;
const font = group('font');

const palette = Object.fromEntries(
  Object.entries(group('palette'))
    .filter(([k]) => !k.startsWith('$'))
    .map(([hue, shades]) => [hue, Object.fromEntries(leaves<string>(shades as Group))]),
);

const themeNames = Object.keys(group('color')).filter((k) => !k.startsWith('$'));
const themes = Object.fromEntries(
  themeNames.map((theme) => [
    theme,
    Object.fromEntries(leaves<string>(group('color')[theme] as Group).map(([k, v]) => [k, resolve(v)])),
  ]),
) as Record<string, Record<string, string>>;

// Every theme must define every semantic colour, or a component would render unstyled in one theme.
const reference = Object.keys(themes[themeNames[0]!]!);
for (const theme of themeNames) {
  const keys = Object.keys(themes[theme]!);
  const missing = reference.filter((k) => !keys.includes(k));
  const extra = keys.filter((k) => !reference.includes(k));
  if (missing.length || extra.length) {
    throw new Error(`Theme "${theme}" mismatch. Missing: [${missing}] Extra: [${extra}]`);
  }
}

const fontSize = leaves<string>(font.size as Group);
const lineHeight = Object.fromEntries(leaves<string>(font.lineHeight as Group));
const fontWeight = leaves<number>(font.weight as Group);
const fontFamily = leaves<string[]>(font.family as Group);
const spacing = leaves<string>(group('spacing'));
const radius = leaves<string>(group('radius'));
const shadow = leaves<ShadowLayer[]>(group('shadow'));
const duration = leaves<string>(group('duration'));
const easing = leaves<number[]>(group('easing'));

/* ---------------------------------- web CSS ---------------------------------- */

/** Tailwind v4 uses `_` in theme keys where class names use `.` (p-1.5 → --spacing-1_5). */
const cssKey = (k: string) => k.replace('.', '_');
const decl = (name: string, value: string | number) => `  --${name}: ${value};`;
const fontStack = (families: string[]) =>
  families.map((f) => (/^[\w-]+$/.test(f) && !/^[A-Z]/.test(f) ? f : `'${f}'`)).join(', ');
const cssShadow = (layers: ShadowLayer[]) =>
  layers.map((l) => `${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${l.color}`).join(', ');

function buildCss(): string {
  const out = [
    `/* ${HEADER} */`,
    '',
    '@theme static {',
    '  /* Reset Tailwind defaults: only Mal tokens are available as utilities. */',
    '  --color-*: initial;',
    '  --spacing: initial;',
    '  --spacing-*: initial;',
    '  --radius-*: initial;',
    '  --shadow-*: initial;',
    '  --text-*: initial;',
    '  --font-*: initial;',
    '  --font-weight-*: initial;',
    '',
    `  /* Colour (semantic, ${themeNames[0]} theme values; see theme scopes below) */`,
    ...Object.entries(themes[themeNames[0]!]!).map(([k, v]) => decl(`color-${k}`, v)),
    '',
    '  /* Typography */',
    ...fontFamily.map(([k, v]) => decl(`font-${k}`, fontStack(v))),
    ...fontSize.flatMap(([k, v]) => [decl(`text-${k}`, rem(v)), decl(`text-${k}--line-height`, rem(lineHeight[k]!))]),
    ...fontWeight.map(([k, v]) => decl(`font-weight-${k}`, v)),
    '',
    '  /* Spacing (4px grid) */',
    ...spacing.map(([k, v]) => decl(`spacing-${cssKey(k)}`, k === 'px' ? v : rem(v))),
    '',
    '  /* Radius */',
    ...radius.map(([k, v]) => decl(`radius-${k}`, px(v) >= 9999 ? '9999px' : rem(v))),
    '',
    '  /* Elevation */',
    ...shadow.map(([k, v]) => decl(`shadow-${k}`, cssShadow(v))),
    '',
    '  /* Motion */',
    ...duration.map(([k, v]) => decl(`duration-${k}`, v)),
    ...easing.map(([k, v]) => decl(`ease-${k}`, `cubic-bezier(${v.join(', ')})`)),
    '}',
    '',
    // Runtime theme scopes. Every theme is declared so a light "island" can sit inside a dark page.
    '@layer base {',
  ];
  for (const theme of themeNames) {
    out.push(`  [data-theme='${theme}'] {`, `    color-scheme: ${theme};`);
    for (const [k, v] of Object.entries(themes[theme]!)) out.push(`  ${decl(`color-${k}`, v)}`);
    out.push('  }');
  }
  out.push('}', '');
  return out.join('\n');
}

/* ------------------------------- native / JS TS ------------------------------- */

const ts = (value: unknown) => JSON.stringify(value, null, 2).replace(/"([A-Za-z_$][\w$]*)":/g, '$1:');
const numbers = (entries: Array<[string, string]>) => Object.fromEntries(entries.map(([k, v]) => [k, px(v)]));

function buildTs(): string {
  const shadowNumbers = Object.fromEntries(
    shadow.map(([k, layers]) => [
      k,
      layers.map((l) => ({ color: l.color, offsetX: px(l.offsetX), offsetY: px(l.offsetY), blur: px(l.blur), spread: px(l.spread) })),
    ]),
  );
  const sizes = Object.fromEntries(fontSize.map(([k, v]) => [k, { fontSize: px(v), lineHeight: px(lineHeight[k]!) }]));

  return [
    `/* ${HEADER} */`,
    '/* Dimensions are unitless px numbers (React Native style values). Web uses theme.css instead. */',
    '',
    `export const palette = ${ts(palette)} as const;`,
    '',
    `export const themes = ${ts(themes)} as const;`,
    '',
    'export type ThemeName = keyof typeof themes;',
    `export type SemanticColor = keyof (typeof themes)['${themeNames[0]}'];`,
    '',
    `export const fontFamily = ${ts(Object.fromEntries(fontFamily))} as const;`,
    '',
    `export const fontSize = ${ts(sizes)} as const;`,
    '',
    `export const fontWeight = ${ts(Object.fromEntries(fontWeight.map(([k, v]) => [k, String(v)])))} as const;`,
    '',
    `export const spacing = ${ts(numbers(spacing))} as const;`,
    '',
    `export const radius = ${ts(numbers(radius))} as const;`,
    '',
    `export const shadow = ${ts(shadowNumbers)} as const;`,
    '',
    `export const duration = ${ts(Object.fromEntries(duration.map(([k, v]) => [k, ms(v)])))} as const;`,
    '',
    `export const easing = ${ts(Object.fromEntries(easing))} as const;`,
    '',
  ].join('\n');
}

/* ------------------------------------ io ------------------------------------- */

const outputs: Record<string, string> = {
  'src/styles/theme.css': buildCss(),
  'src/tokens/tokens.generated.ts': buildTs(),
};

if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs).filter(([file, content]) => {
    try {
      return readFileSync(path(file), 'utf8') !== content;
    } catch {
      return true; // a missing file is stale
    }
  });
  if (stale.length > 0) {
    console.error(`✖ ${stale.map(([f]) => f).join(', ')} out of date. Run \`npm run tokens\` and commit the result.`);
    process.exit(1);
  }
  console.log('✔ generated tokens are up to date');
} else {
  for (const [file, content] of Object.entries(outputs)) {
    writeFileSync(path(file), content);
    console.log(`✔ wrote ${file}`);
  }
}
