/**
 * Compiles src/tokens/tokens.ts into src/styles/tokens.css.
 *
 *   node scripts/build-tokens.ts          write the file
 *   node scripts/build-tokens.ts --check  exit 1 if the committed file is stale (CI)
 *
 * The output does two jobs:
 *  1. A Tailwind `@theme` block that *replaces* Tailwind's default palette and
 *     scales. Only Mal tokens exist as utilities, so `bg-emerald-600` or `p-7`
 *     simply don't compile. That's the cheapest governance there is.
 *  2. Theme scopes (`[data-theme="dark"]`) that remap the semantic colour
 *     variables at runtime. Components never know which theme is active.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  motion,
  radius,
  shadow,
  spacing,
  themes,
  typography,
} from '../src/tokens/tokens.ts';

const OUT = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url));

/** Tailwind v4 uses `_` in theme keys where class names use `.` (p-1.5 → --spacing-1_5). */
const key = (k: string | number) => String(k).replace('.', '_');

const decl = (name: string, value: string) => `  --${name}: ${value};`;

function buildCss(): string {
  const lines: string[] = [];
  const push = (...l: string[]) => lines.push(...l);

  push(
    '/* AUTO-GENERATED by scripts/build-tokens.ts from src/tokens/tokens.ts. Do not edit by hand. */',
    '',
    '@theme static {',
    '  /* Reset Tailwind defaults: only Mal tokens are available as utilities. */',
    '  --color-*: initial;',
    '  --spacing: initial;',
    '  --spacing-*: initial;',
    '  --radius-*: initial;',
    '  --shadow-*: initial;',
    '  --text-*: initial;',
    '  --font-*: initial;',
    '  --font-weight-*: initial;',
    '',
  );

  push('  /* Colour (semantic, light theme values; see theme scopes below) */');
  for (const [name, value] of Object.entries(themes.light)) push(decl(`color-${name}`, value));

  push('', '  /* Typography */');
  for (const [name, value] of Object.entries(typography.fontFamily)) push(decl(`font-${name}`, value));
  for (const [name, [size, lh]] of Object.entries(typography.fontSize)) {
    push(decl(`text-${name}`, size), decl(`text-${name}--line-height`, lh));
  }
  for (const [name, value] of Object.entries(typography.fontWeight)) push(decl(`font-weight-${name}`, value));

  push('', '  /* Spacing (4px grid) */');
  for (const [name, value] of Object.entries(spacing)) push(decl(`spacing-${key(name)}`, value));

  push('', '  /* Radius */');
  for (const [name, value] of Object.entries(radius)) push(decl(`radius-${name}`, value));

  push('', '  /* Elevation */');
  for (const [name, value] of Object.entries(shadow)) push(decl(`shadow-${name}`, value));

  push('', '  /* Motion */');
  for (const [name, value] of Object.entries(motion.duration)) push(decl(`duration-${name}`, value));
  for (const [name, value] of Object.entries(motion.easing)) push(decl(`ease-${name}`, value));
  push('}', '');

  // Runtime theme scopes. Light is re-declared so a light "island" can be nested in a dark page.
  push('@layer base {');
  for (const [theme, colors] of Object.entries(themes)) {
    push(`  [data-theme='${theme}'] {`, `    color-scheme: ${theme};`);
    for (const [name, value] of Object.entries(colors)) push(`  ${decl(`color-${name}`, value)}`);
    push('  }');
  }
  push('}', '');

  return lines.join('\n');
}

const css = buildCss();

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing file is stale */
  }
  if (current !== css) {
    console.error('✖ src/styles/tokens.css is out of date. Run `npm run tokens` and commit the result.');
    process.exit(1);
  }
  console.log('✔ tokens.css is up to date');
} else {
  writeFileSync(OUT, css);
  console.log(`✔ wrote ${OUT}`);
}
